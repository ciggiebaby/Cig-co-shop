#!/usr/bin/env python3
"""Build shipping-returns.html and faq.html from the approved copy (Markdown).

Copy source of truth (approved by CIG via SERVI, 2026-10-22):
  docs/policies/shipping-returns.md, docs/policies/faq.md
Re-run after editing the copy:  python3 scripts/build-policy-pages.py
Needs: pip install markdown
"""
import re, pathlib, markdown, html

ROOT = pathlib.Path(__file__).resolve().parent.parent
LAST_UPDATED = "October 22, 2026"
EMAIL = "orders@cigcompany.com"

index = (ROOT / "index.html").read_text()
# Reuse the live cart drawer + checkout modal + product modal from index.html so
# the header BAG button and checkout work the same on these pages.
def between(start, end):
    i = index.index(start); j = index.index(end, i) + len(end)
    return index[i:j]
product_modal = between("<!-- Product detail modal -->", "</div>\n</div>\n")
cart_drawer = between("<!-- Cart drawer -->", '<div id="cart-backdrop" class="backdrop"></div>')
checkout_modal = between("<!-- Checkout modal -->", "</div>\n  </div>\n</div>\n")
footer = between('<footer class="site-footer">', "</footer>")

def render(md_text, faq=False):
    if faq:
        # A bold line on its own is a question: make it an <h3> (same words).
        md_text = re.sub(r"(?m)^\*\*(.+?)\*\*\s*$", r"### \1", md_text)
    md_text = md_text.replace("[publish date]", LAST_UPDATED)
    # Python-Markdown wants a blank line before a list and 4-space nesting;
    # the approved copy uses GitHub style. Normalize without touching wording.
    md_text = re.sub(r"(?m)^ {2,3}(- )", r"    \1", md_text)
    lines, out = md_text.split("\n"), []
    is_item = lambda l: bool(re.match(r"\s*(- |\d+\. )", l))
    for l in lines:
        if out and is_item(l) and out[-1].strip() and not is_item(out[-1]) and not out[-1].startswith("|"):
            out.append("")
        out.append(l)
    md_text = "\n".join(out)
    body = markdown.markdown(md_text, extensions=["tables", "sane_lists"])
    body = body.replace(EMAIL, f'<a href="mailto:{EMAIL}">{EMAIL}</a>')
    # Drop the H1 from the body; it becomes the page title block.
    m = re.match(r"\s*<h1>(.*?)</h1>\s*", body, re.S)
    title = m.group(1) if m else ""
    body = body[m.end():] if m else body
    # Wrap tables so they scroll on phones.
    body = body.replace("<table>", '<div class="policy-table-wrap"><table>').replace("</table>", "</table></div>")
    return title, body

